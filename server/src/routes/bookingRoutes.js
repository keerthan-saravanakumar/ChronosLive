const router = require('express').Router();
const { auth, authorize } = require('../middlewares/auth');
const validate = require('../middlewares/validate');
const schemas = require('../validators/resources');
const { z, route, empty, pagination } = require('../validators/common');
const c = require('../controllers/bookingController');
const wrap = require('../utils/asyncHandler');
router.use(auth);
router.post('/slots/:id/book', validate(schemas.id), wrap(c.book));
router.delete('/bookings/:id', validate(schemas.cancel), wrap(c.cancel));
router.get('/bookings/me', validate(route(empty, empty, z.object({ status: z.enum(['upcoming', 'past', 'cancelled']).default('upcoming') }).strict())), wrap(c.mine));
router.patch('/slots/:id', authorize('organizer'), validate(schemas.capacity), wrap(c.capacity));
router.post('/slots/:id/cancel', authorize('organizer'), validate(schemas.cancel), wrap(c.cancelSlot));
router.post('/slots/:id/waitlist', validate(schemas.id), wrap(c.join));
router.delete('/slots/:id/waitlist', validate(schemas.id), wrap(c.leave));
router.get('/waitlist/me', validate(route()), wrap(c.waitlist));
router.get('/notifications', validate(route(empty, empty, z.object(pagination).strict())), wrap(c.notifications));
router.patch('/notifications/read-all', validate(route()), wrap(c.read));
router.patch('/notifications/:id/read', validate(schemas.id), wrap(c.read));
module.exports = router;
